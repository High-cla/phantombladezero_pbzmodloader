'use strict';
// Builds the one script the DLL carries: script-bootstrap.js with script-manager.js inside it.
// The source files stay normal editable files; only build/embedded_script.hpp holds the result.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
// The script replaces a game script in that script's own memory, so it must fit the smallest
// slot of src/signatures.hpp. The DLL has a safe fallback; this catches it at build time.
const limit = 12 * 1024;
const read = name => fs.readFileSync(path.join(root, 'src', name), 'utf8').replace(/\r\n/g, '\n');

function compose() {
    const manager = read('script-manager.js');
    const bootstrap = read('script-bootstrap.js');
    const marker = "const manager = require('./manager');";
    if (bootstrap.split(marker).length !== 2) throw new Error('script-bootstrap.js must load the manager exactly once');
    const inlined = 'const manager = (function () {\nconst exports = {};\n' + manager + '\nreturn exports;\n})();';
    return bootstrap.replace(marker, () => inlined);
}

function write() {
    const bytes = Buffer.from(compose(), 'utf8');
    if (bytes.length > limit) throw new Error('Embedded script is ' + bytes.length + ' bytes; the limit is ' + limit);
    const rows = [];
    for (let i = 0; i < bytes.length; i += 32) rows.push(Array.from(bytes.subarray(i, i + 32)).join(','));
    const out = path.join(root, 'build/embedded_script.hpp');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, '#pragma once\n// Generated by scripts/embed-script.cjs. Do not edit.\n' +
        'static const unsigned char embeddedScriptBytes[]={\n' + rows.join(',\n') + '\n};\n' +
        'static const char* const embeddedScript=(const char*)embeddedScriptBytes;\n' +
        'static const size_t embeddedScriptSize=' + bytes.length + ';\n');
    console.log('Embedded script: ' + bytes.length + ' of ' + limit + ' bytes.');
}

if (require.main === module) write();
module.exports = { compose, limit };
